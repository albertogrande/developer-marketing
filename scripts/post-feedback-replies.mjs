#!/usr/bin/env node
// Close out the reader-feedback loop. The weekly writer answers the issues it
// processed by writing editorial/FEEDBACK-REPLIES.md (gitignored, one block
// per issue); this posts each reply as an issue comment — with the Claude
// attribution footer — and closes the ones the writer marked resolved. Runs
// after the gates and the commit, so an answered correction is always an
// applied correction.
//
// File format (parsed strictly; anything else is skipped with a warning):
//   ## #<issue-number> close|keep-open
//   <reply markdown…>
//
// Dry run: node scripts/post-feedback-replies.mjs --dry-run

import { readFileSync, existsSync, writeFileSync, mkdtempSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const FILE = 'editorial/FEEDBACK-REPLIES.md';
const DRY = process.argv.includes('--dry-run');
const FOOTER = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_';

if (!existsSync(FILE)) {
  console.log('post-feedback-replies: no replies file — nothing to post.');
  process.exit(0);
}

const text = readFileSync(FILE, 'utf8');
const blocks = [...text.matchAll(/^## #(\d+) (close|keep-open)\s*$/gm)];
if (!blocks.length) {
  console.log('post-feedback-replies: replies file has no reply blocks — nothing to post.');
  process.exit(0);
}

const scratch = mkdtempSync(join(tmpdir(), 'feedback-replies-'));
let posted = 0;
for (let i = 0; i < blocks.length; i++) {
  const [, number, action] = blocks[i];
  const start = blocks[i].index + blocks[i][0].length;
  const end = i + 1 < blocks.length ? blocks[i + 1].index : text.length;
  const reply = text.slice(start, end).trim();
  if (!reply) {
    console.warn(`warn: #${number} has an empty reply — skipped.`);
    continue;
  }
  const bodyFile = join(scratch, `reply-${number}.md`);
  writeFileSync(bodyFile, reply + FOOTER);
  if (DRY) {
    console.log(`[dry-run] would comment on #${number} (${action}):\n${reply}\n`);
    continue;
  }
  try {
    execFileSync('gh', ['issue', 'comment', number, '--body-file', bodyFile], {
      stdio: 'inherit',
    });
    if (action === 'close') {
      execFileSync('gh', ['issue', 'close', number, '--reason', 'completed'], {
        stdio: 'inherit',
      });
    }
    posted++;
  } catch (e) {
    // One failed reply must not sink the rest — the issue stays open and the
    // next weekly run sees it again.
    console.warn(`warn: posting to #${number} failed: ${e.message}`);
  }
}
console.log(`post-feedback-replies: ${posted}/${blocks.length} replies posted.`);
