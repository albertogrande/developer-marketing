#!/usr/bin/env node
// Regenerates editorial/COVERAGE.md — one line per published piece across the
// dated collections — from the content itself. The desks used to hand-append
// coverage lines to MEMORY.md, which drifted and got pruned; this index is
// derived, so it can never lie and never needs pruning. It is the novelty
// check: before writing, a desk greps here for what has already run —
// including everything past MEMORY's pruning horizon.
//
// Deterministic by construction (content frontmatter only, no clock), so the
// editorial-gates step can regenerate it and `git diff --exit-code` proves
// idempotence.

import { writeFileSync } from 'node:fs';
import { contentEntries } from './lib/routes.mjs';

const COVERED = ['articles', 'deep-dives', 'issues', 'signals'];
const LABEL = { articles: 'article', 'deep-dives': 'dive', issues: 'issue', signals: 'signals' };

const day = (v) =>
  v instanceof Date ? v.toISOString().slice(0, 10) : String(v ?? '').slice(0, 10);
const clip = (s, n = 100) => {
  const t = String(s ?? '').replace(/\s+/g, ' ').trim();
  return t.length > n ? `${t.slice(0, n - 1)}…` : t;
};

const rows = [];
for (const { collection, id, fm } of contentEntries()) {
  if (!COVERED.includes(collection) || !fm) continue;
  rows.push({
    date: day(fm.date),
    kind: LABEL[collection],
    id,
    title: fm.title ?? id,
    tags: (fm.tags ?? []).join(', '),
    summary: clip(fm.summary),
  });
}
rows.sort((a, b) => b.date.localeCompare(a.date) || a.kind.localeCompare(b.kind) || a.id.localeCompare(b.id));

const out = [
  '# Published coverage index',
  '',
  'Generated by `scripts/build-coverage-index.mjs` from content frontmatter —',
  '**do not edit by hand**; the editorial gates regenerate it on every run.',
  'One line per published piece, newest first. This is the novelty check:',
  'grep here before writing, it covers everything ever published including',
  "pieces past MEMORY.md's pruning horizon.",
  '',
  ...rows.map(
    (r) =>
      `- ${r.date} · ${r.kind} · \`${r.id}\` · *${r.title}*${r.tags ? ` · ${r.tags}` : ''}${r.summary ? ` — ${r.summary}` : ''}`
  ),
  '',
].join('\n');

writeFileSync('editorial/COVERAGE.md', out);
console.log(`build-coverage-index: ${rows.length} entries → editorial/COVERAGE.md`);
